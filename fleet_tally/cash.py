"""Daily cash fuel sales (MS / HSD / XG) -> Tally Sales vouchers.

The cash counter's sales are entered in Tally as one Sales voucher per product
per day — imported as "Cash MS", "HSD CASH" and "XG CASH", each voucher
numbered by its date (Cash/MS/1Oct2026, Cash/HSD/1Oct2026, Cash/XG/1Oct2026),
so there is no starting number to keep track of; party Cash,
one stock line (quantity in LTR at the day's price), godown Main Location,
batch Primary Batch, posted to the product's sales ledger. Each is generated by
cloning a REAL exported voucher of that type (templates/CASH_*.xml) and setting
only the date, voucher number, quantity, rate and amount — exactly as with the
fleet / TDS journals.

The amount is quantity x price rounded to paise (half up), which is how every
cash voucher in the books was computed. Voucher numbers are explicit
(Cash/<product>/<date>), because Tally
silently drops about half of number-less vouchers on a bulk import; the voucher
types must allow it ("Automatic (Manual Override)").

The sheet: one tab per product (MS, HSD, XG), columns Date, Quantity, Price.
"""

from __future__ import annotations

import datetime as dt
import os
import re
from dataclasses import dataclass
from decimal import ROUND_HALF_UP, Decimal, InvalidOperation

from . import generate as G
from . import parse as P

TEMPLATE_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "templates")

# "vchtype" is the voucher type the vouchers are imported as; the template is a
# real voucher of "tpl_vchtype". MS imports go to their own type "Cash MS"
# (Automatic (Manual Override)) so the hand-entered "MS Cash" vouchers are left
# exactly as they are; HSD CASH and XG CASH already allow a manual number.
# Every voucher is numbered by its date: prefix + 1Oct2026 (one per product per day).
PRODUCTS = {
    "MS":  {"file": "CASH_MS.xml",  "vchtype": "Cash MS",  "tpl_vchtype": "MS Cash",
            "prefix": "Cash/MS/",
            "item": "Motor Spirit", "ledger": "SALE (MS)", "label": "Motor Spirit (petrol)"},
    "HSD": {"file": "CASH_HSD.xml", "vchtype": "HSD CASH", "prefix": "Cash/HSD/",
            "item": "High Speed Diesel", "ledger": "SALE (HSD)", "label": "High Speed Diesel"},
    "XG":  {"file": "CASH_XG.xml",  "vchtype": "XG CASH",  "prefix": "Cash/XG/",
            "item": "XtraGreen Diesel", "ledger": "SALE (HSD)", "label": "XtraGreen Diesel"},
}
# A price outside this range (Rs per litre) is almost certainly a typo or the
# day's total typed into the Price column.
PRICE_RANGE = (Decimal("20"), Decimal("500"))

_DATE_TAGS = ["DATE", "VCHSTATUSDATE", "EFFECTIVEDATE"]
# Tally's own identity fields — removed so each voucher imports as a new one.
# (The voucher number is replaced in place, not removed.)
_STRIP_TAGS = ["GUID", "ALTERID", "MASTERID", "VOUCHERKEY", "VOUCHERRETAINKEY"]


@dataclass
class CashRow:
    product: str
    index: int                  # row number in its sheet (1 = first data row)
    date: dt.date | None
    qty: Decimal | None
    price: Decimal | None
    error: str = ""

    @property
    def amount(self) -> Decimal:
        return (self.qty * self.price).quantize(Decimal("0.01"), ROUND_HALF_UP)


def _dec(v) -> Decimal | None:
    if v is None or v == "":
        return None
    if isinstance(v, (int, float)) and not isinstance(v, bool):
        return Decimal(repr(v)) if isinstance(v, float) else Decimal(v)
    s = re.sub(r"[,\s₹]|Rs\.?|/LTR|LTR|L$", "", str(v), flags=re.I).strip()
    try:
        return Decimal(s)
    except InvalidOperation:
        return None


def _rate_str(price: Decimal) -> str:
    """Tally's rate text: at least 2 decimals, more only if the price has them."""
    p = price.normalize()
    places = max(2, -p.as_tuple().exponent if p.as_tuple().exponent < 0 else 0)
    return f"{price:.{places}f}"


# ---- reading the sheet ------------------------------------------------------

def product_of(sheet_name: str, title_text: str = "") -> str | None:
    """Which product a tab holds, from its name (or its title note)."""
    for text in (sheet_name, title_text):
        t = f" {re.sub(r'[^A-Z]+', ' ', (text or '').upper())} "
        if " XG " in t or "XTRA" in t or "XTRAGREEN" in t:
            return "XG"
        if " HSD " in t or "DIESEL" in t:
            return "HSD"
        if " MS " in t or "PETROL" in t or "MOTOR SPIRIT" in t:
            return "MS"
    return None


def _header(grid):
    """(row, date col, qty col, price col) of the first row labelling all three."""
    for i, r in enumerate(grid[:25]):
        cells = [str(c or "").strip().lower() for c in r]

        def col(*needles):
            for j, h in enumerate(cells):
                if h and len(h) <= 30 and any(n in h for n in needles):
                    return j
            return None
        cd, cq, cp = col("date"), col("quantity", "qty", "litre", "liter", "ltr"), \
            col("price", "rate")
        if None not in (cd, cq, cp) and len({cd, cq, cp}) == 3:
            return i, cd, cq, cp
    return None


def rows_from_sheet(product: str, grid) -> tuple[list[CashRow], str]:
    """Rows of one product tab; second value is a problem with the tab ("" if ok)."""
    found = _header(grid)
    if not found:
        return [], "no Date / Quantity / Price header row"
    hi, cd, cq, cp = found
    out = []
    for n, r in enumerate(grid[hi + 1:], start=1):
        def cell(j):
            return r[j] if j < len(r) else None
        raw_d, raw_q, raw_p = cell(cd), cell(cq), cell(cp)
        if all(x in (None, "") for x in (raw_d, raw_q, raw_p)):
            continue
        date, qty, price = P._to_date(raw_d), _dec(raw_q), _dec(raw_p)
        err = ""
        if date is None:
            err = "unreadable date"
        elif qty is None:
            err = "unreadable quantity"
        elif qty <= 0:
            err = "quantity must be more than zero"
        elif price is None:
            err = "unreadable price"
        elif not PRICE_RANGE[0] <= price <= PRICE_RANGE[1]:
            err = (f"price {price} per litre looks wrong (expected "
                   f"{PRICE_RANGE[0]}–{PRICE_RANGE[1]}) — the day's total in the Price column?")
        out.append(CashRow(product, n, date, qty, price, err))
    return out, ""


def read_workbook(path: str) -> tuple[list[CashRow], list[str]]:
    """All product tabs of a cash-sales workbook -> rows, problems."""
    rows, problems, seen = [], [], set()
    for name, grid in _sheets(path):
        title = " ".join(str(c or "") for r in grid[:3] for c in r)
        prod = product_of(name, title)
        if prod is None:
            if any(any(c not in (None, "") for c in r) for r in grid):
                problems.append(f"sheet '{name}': can't tell the product — name the tab MS, HSD or XG")
            continue
        if prod in seen:
            problems.append(f"sheet '{name}': a second {prod} tab — only the first is used")
            continue
        seen.add(prod)
        got, err = rows_from_sheet(prod, grid)
        if err:
            problems.append(f"sheet '{name}': {err}")
        rows += got
    return rows, problems


def _sheets(path: str):
    if path.lower().endswith((".xlsx", ".xlsm")):
        import openpyxl
        wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
        return [(ws.title, [list(r) for r in ws.iter_rows(values_only=True)])
                for ws in wb.worksheets]
    import xlrd
    book = xlrd.open_workbook(path)
    out = []
    for sh in book.sheets():
        grid = []
        for i in range(sh.nrows):
            row = []
            for j in range(sh.ncols):
                c = sh.cell(i, j)
                if c.ctype == xlrd.XL_CELL_DATE:
                    y, m, d, *_ = xlrd.xldate_as_tuple(c.value, book.datemode)
                    row.append(dt.date(y, m, d))
                else:
                    row.append(c.value)
            grid.append(row)
        out.append((sh.name, grid))
    return out


# ---- building vouchers -------------------------------------------------------

def _read_template(name: str) -> str:
    with open(os.path.join(TEMPLATE_DIR, name), encoding="utf-8") as fh:
        return fh.read()


def _strip_identity(vch: str) -> str:
    for tag in _STRIP_TAGS:
        vch = re.sub(rf"\s*<{tag}>[^<]*</{tag}>", "", vch)
    vch = re.sub(r'\s+REMOTEID="[^"]*"', "", vch, count=1)
    return re.sub(r'\s+VCHKEY="[^"]*"', "", vch, count=1)


_MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]


def voucher_number(product: str, day: dt.date) -> str:
    """The voucher number is the date: Cash/MS/1Oct2026, Cash/HSD/25Dec2026.
    The month is fixed English (not the computer's locale)."""
    return f"{PRODUCTS[product]['prefix']}{day.day}{_MONTHS[day.month - 1]}{day.year}"


def make_cash_sale(product: str, ymd: str, qty: Decimal, price: Decimal,
                   number: str) -> str:
    """One cash Sales voucher: ``qty`` LTR of ``product`` at ``price``."""
    k = PRODUCTS[product]
    qty, price = Decimal(qty), Decimal(price)
    amount = (qty * price).quantize(Decimal("0.01"), ROUND_HALF_UP)
    vch = _strip_identity(_read_template(k["file"]))
    tpl_type = k.get("tpl_vchtype", k["vchtype"])
    if tpl_type != k["vchtype"]:                 # e.g. a real "MS Cash" voucher -> "Cash MS"
        vch = vch.replace(f'VCHTYPE="{tpl_type}"', f'VCHTYPE="{k["vchtype"]}"')
        vch = vch.replace(f">{tpl_type}<", f">{k['vchtype']}<")
    for tag in _DATE_TAGS:
        vch = re.sub(rf"<{tag}>[^<]*</{tag}>", f"<{tag}>{ymd}</{tag}>", vch)
    vch = re.sub(r"<NUMBERINGSTYLE>[^<]*</NUMBERINGSTYLE>",
                 "<NUMBERINGSTYLE>Automatic (Manual Override)</NUMBERINGSTYLE>", vch)
    vch = re.sub(r"<VOUCHERNUMBER>[^<]*</VOUCHERNUMBER>",
                 f"<VOUCHERNUMBER>{G._esc(number)}</VOUCHERNUMBER>", vch, count=1)
    q = f" {qty:.3f} LTR"
    vch = re.sub(r"<ACTUALQTY>[^<]*</ACTUALQTY>", f"<ACTUALQTY>{q}</ACTUALQTY>", vch)
    vch = re.sub(r"<BILLEDQTY>[^<]*</BILLEDQTY>", f"<BILLEDQTY>{q}</BILLEDQTY>", vch)
    vch = re.sub(r"<RATE>[^<]*</RATE>", f"<RATE>{_rate_str(price)}/LTR</RATE>", vch)

    # The stock line, its batch and its sales-ledger allocation carry +amount;
    # the party (Cash) ledger -amount — every AMOUNT is set by where it sits.
    def inv(m):
        return re.sub(r"<AMOUNT>[^<]*</AMOUNT>", f"<AMOUNT>{amount:.2f}</AMOUNT>", m.group(0))
    vch = re.sub(r"<ALLINVENTORYENTRIES\.LIST>.*?</ALLINVENTORYENTRIES\.LIST>", inv, vch,
                 flags=re.S)

    def led(m):
        return re.sub(r"<AMOUNT>[^<]*</AMOUNT>", f"<AMOUNT>-{amount:.2f}</AMOUNT>", m.group(0))
    vch = re.sub(r"<LEDGERENTRIES\.LIST>.*?</LEDGERENTRIES\.LIST>", led, vch, flags=re.S)
    return vch


def cash_balances(vch: str) -> bool:
    """Stock-line value equals the party ledger (Dr Cash = Cr Sales)."""
    inv = re.search(r"<ALLINVENTORYENTRIES\.LIST>.*?<AMOUNT>(-?[\d.]+)</AMOUNT>", vch, re.S)
    led = re.findall(r"<LEDGERENTRIES\.LIST>.*?<AMOUNT>(-?[\d.]+)</AMOUNT>", vch, re.S)
    return bool(inv and led) and abs(float(inv.group(1)) + sum(map(float, led))) < 0.005


def process(rows: list[CashRow]) -> tuple[list[str], list[dict], dict]:
    """Vouchers for every valid row, oldest date first, each numbered by its date
    (Cash/MS/1Oct2026) — so one row per product per day. Returns
    ``(vouchers, entries, summary)``."""
    vouchers, entries = [], []
    per = {}
    for prod in PRODUCTS:
        mine = sorted([r for r in rows if r.product == prod],
                      key=lambda r: (r.date or dt.date.min, r.index))
        seen = set()                             # the day IS the number: one row per day
        for r in mine:
            if r.error:
                continue
            if r.date in seen:
                r.error = (f"a second {prod} row for {r.date:%d-%m-%Y} — {PRODUCTS[prod]['vchtype']} "
                           "is numbered by its date, so combine them into one row")
            seen.add(r.date)
        n_ok = 0
        total = Decimal("0")
        used = []
        for r in mine:
            base = {"kind": "cash", "product": prod, "index": r.index,
                    "date": r.date.strftime("%d-%m-%Y") if r.date else "",
                    "qty": f"{r.qty:.3f}" if r.qty is not None else "",
                    "price": _rate_str(r.price) if r.price is not None else "",
                    "amount": "", "voucher_no": "", "status": "ok", "note": ""}
            if r.error:
                entries.append({**base, "status": "error", "note": r.error})
                continue
            number = voucher_number(prod, r.date)
            vch = make_cash_sale(prod, r.date.strftime("%Y%m%d"), r.qty, r.price, number)
            if not cash_balances(vch):
                entries.append({**base, "status": "error", "note": "voucher did not balance"})
                continue
            vouchers.append(vch)
            used.append(number)
            n_ok += 1
            total += r.amount
            entries.append({**base, "amount": f"{r.amount:.2f}", "voucher_no": number})
        per[prod] = {"n_vouchers": n_ok, "n_error": sum(1 for r in mine if r.error),
                     "total_amount": f"{total:.2f}",
                     "first": used[0] if used else "",
                     "last": used[-1] if used else ""}
    summary = {"products": per, "n_vouchers": len(vouchers),
               "n_error": sum(p["n_error"] for p in per.values()),
               "all_balance": all(cash_balances(v) for v in vouchers)}
    return vouchers, entries, summary
